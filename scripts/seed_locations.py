def _all_seed_rows():
    """LOCATIONS (all Tier A) + EXPANSION as uniform 7-tuples."""
    for name, lat, lon, tz, country, coastal in LOCATIONS:
        yield (name, lat, lon, tz, country, coastal, 1)
    yield from EXPANSION


def seed(conn: sqlite3.Connection) -> dict:
    inserted, skipped = [], []
    has_tier = "collect_every_hours" in {
        r[1] for r in conn.execute("PRAGMA table_info(locations)")}
    for name, lat, lon, tz, country, coastal, tier in _all_seed_rows():
        row = conn.execute(
            """SELECT id FROM locations
               WHERE ABS(latitude - ?) < 0.05 AND ABS(longitude - ?) < 0.05
               ORDER BY id LIMIT 1""", (lat, lon)).fetchone()
        if row:
            skipped.append(name)
            continue
        if has_tier:
            conn.execute(
                """INSERT INTO locations (name, latitude, longitude, timezone,
                                          country, is_coastal,
                                          collect_every_hours, created_at)
                   VALUES (?,?,?,?,?,?,?,?)""",
                (name, lat, lon, tz, country, coastal, tier, utc_iso()))
        else:  # pre-migration DB: column absent, DB default tier applies
            conn.execute(
                """INSERT INTO locations (name, latitude, longitude, timezone,
                                          country, is_coastal, created_at)
                   VALUES (?,?,?,?,?,?,?)""",
                (name, lat, lon, tz, country, coastal, utc_iso()))
        inserted.append(name)
    conn.commit()
    return {"inserted": inserted, "skipped_existing": skipped}


def main() -> None:
    conn = dbmod.connect()
    try:
        result = seed(conn)
        total = conn.execute("SELECT COUNT(*) FROM locations").fetchone()[0]
        named = conn.execute(
            "SELECT COUNT(*) FROM locations WHERE country IS NOT NULL").fetchone()[0]
        countries = conn.execute(
            "SELECT COUNT(DISTINCT country) FROM locations "
            "WHERE country IS NOT NULL").fetchone()[0]
        tiers = conn.execute(
            "SELECT collect_every_hours, COUNT(*) FROM locations "
            "WHERE country IS NOT NULL GROUP BY 1 ORDER BY 1").fetchall()
    finally:
        conn.close()
    print(f"inserted: {len(result['inserted'])}")
    print(f"skipped (already present): {len(result['skipped_existing'])}")
    print(f"locations total: {total}, with country (collectable): {named}")
    print(f"distinct countries covered: {countries}")
    runs = 0
    for interval, n in tiers:
        per_day = 24 // interval if interval else 24
        runs += n * per_day
        print(f"  tier {interval}h: {n} locations x {per_day} runs/day")
    print(f"projected location-runs/day: {runs}")


if __name__ == "__main__":
    main()
