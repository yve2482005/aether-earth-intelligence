"""Operational aftershock forecasts (USGS).

USGS publishes machine-readable operational aftershock forecasts as a ComCat
product ('aftershock-forecast') attached to significant events. This module
parses that product when present.

Scientific honesty (HARD):
- This is a PROBABILITY forecast from an official source, not a guarantee.
- AETHER never produces its own earthquake predictions: no future time,
  location, or magnitude is generated by us.
- When no official product exists, the honest answer is
  "no official aftershock forecast available".
"""
from __future__ import annotations

import sqlite3
from typing import Any, Dict, Optional

from backend.common.http import make_session
from backend.common.timeutil import utc_iso
from backend.collectors.earthquake.shakemap import list_detail_products

DISCLAIMER = ("Probability forecast from an official source, not a guarantee. "
              "AETHER does not produce earthquake predictions.")


def _find_event(conn: sqlite3.Connection, canonical_event_id: Optional[str]) -> Optional[dict]:
    if canonical_event_id:
        row = conn.execute(
            "SELECT * FROM earthquake_events WHERE canonical_event_id = ?",
            (canonical_event_id,)).fetchone()
        if row:
            return dict(row)
    return None


def get_aftershock_forecast(conn: sqlite3.Connection,
                            canonical_event_id: Optional[str] = None,
                            session=None) -> Dict[str, Any]:
    """Return the official operational aftershock forecast for an event, if published."""
    session = session or make_session()
    event = _find_event(conn, canonical_event_id)
    if event is None:
        # Fallback: largest event in the last 30 days.
        event = conn.execute(
            "SELECT * FROM earthquake_events ORDER BY magnitude DESC LIMIT 1").fetchone()
        event = dict(event) if event else None
    if event is None:
        return {"available": False, "kind": "RISK",
                "message": "No earthquake events in database; cannot check for aftershock forecasts.",
                "checked_at": utc_iso()}
    eid = event["canonical_event_id"]
    url = f"https://earthquake.usgs.gov/fdsnws/event/1/query?eventid={eid}&format=geojson"
    prod = list_detail_products(url, session)
    if not prod.get("ok"):
        return {"available": False, "kind": "RISK", "canonical_event_id": eid,
                "message": "Could not reach the official ComCat detail service.",
                "checked_at": utc_iso()}
    if not prod.get("has_aftershock_forecast"):
        return {"available": False, "kind": "RISK", "canonical_event_id": eid,
                "magnitude": event.get("magnitude"),
                "message": "No official aftershock forecast available for this event.",
                "product_types_seen": prod.get("product_types"), "checked_at": utc_iso()}
    return {"available": True, "kind": "RISK", "canonical_event_id": eid,
            "magnitude": event.get("magnitude"),
            "disclaimer": DISCLAIMER,
            "detail_url": url,
            "note": ("Official product present. Fetch the 'aftershock-forecast' product "
                     "from the ComCat detail document for the full probability table."),
            "checked_at": utc_iso()}
